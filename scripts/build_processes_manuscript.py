# ---------------------------------------------------------------- cross-references and floats (MDPI conventions)
def floats(t):
    t = t.replace(r"Figs.~\ref", r"Figures~\ref").replace(r"Fig.~\ref", r"Figure~\ref")
    t = re.sub(r"\(\\ref\{app:", r"(Appendix~\\ref{app:", t)
    t = re.sub(r"in \\ref\{app:", r"in Appendix~\\ref{app:", t)
    t = re.sub(r"(?<![~{])\\ref\{app:", r"Appendix~\\ref{app:", t)
    t = t.replace("Appendix~Appendix~", "Appendix~")
    # full-width figures: MDPI adjustwidth into the left margin
    def fig(m):
        inner = m.group(1)
        if "adjustwidth" in inner:          # already in MDPI form
            return m.group(0)
        cap = inner[inner.index(r"\caption"):]
        graphics = inner[:inner.index(r"\caption")].replace(r"\centering", "").strip()
        graphics = graphics.replace(r"width=\textwidth", r"width=\linewidth").replace(r"width=\linewidth", r"width=\linewidth")
        return ("\\begin{figure}[H]\n\\begin{adjustwidth}{-\\extralength}{0cm}\n\\centering\n" + graphics +
                "\n\\end{adjustwidth}\n" + cap.strip() + "\n\\end{figure}")
    t = re.sub(r"\\begin\{figure\*?\}\[[^\]]*\]\n(.*?)\\end\{figure\*?\}", fig, t, flags=re.S)
    t = re.sub(r"\\begin\{table\*?\}\[[^\]]*\]", r"\\begin{table}[H]", t).replace(r"\end{table*}", r"\end{table}")
    return t


