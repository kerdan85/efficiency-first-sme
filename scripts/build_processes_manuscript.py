def numeric(t):
    t = re.sub(r"\\citep\{", r"\\cite{", t)
    t = re.sub(r"reported by \\citealp\{([^}]*)\}", r"reported in \\cite{\1}", t)
    t = re.sub(r"\\citealp\{", r"\\cite{", t)
    # put citations before punctuation is MDPI style already; ensure non-breaking space
    t = re.sub(r"\\MXN\\ \\cite\{", r"\\MXN{}~\\cite{", t)
    t = re.sub(r"(?<!\\) \\cite\{", r"~\\cite{", t)
    return t


